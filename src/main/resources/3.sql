-- =====================================================================
-- OIDC / OAuth2 configuration store
-- Target: PostgreSQL 19
--
-- Conventions used here:
--   * Identity columns instead of serial (SQL-standard; serial's
--     separate sequence object and ownership rules are legacy).
--   * Every child table carries a natural-key UNIQUE constraint whose
--     LEADING column is its foreign key. That one index both enforces
--     uniqueness and serves the FK, so ON DELETE CASCADE never has to
--     sequentially scan the child, and no separate FK index is needed.
--   * JSON payloads are jsonb, not text, so they can be validated,
--     indexed and queried.
-- =====================================================================

START TRANSACTION;

-- ---------------------------------------------------------------------
-- API Resources (the protected APIs / resource servers)
-- ---------------------------------------------------------------------
CREATE TABLE api_resources (
    id                                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                                    varchar(200) NOT NULL,
    display_name                            varchar(200),
    description                             varchar(1000),
    enabled                                 bool NOT NULL DEFAULT true,
    show_in_discovery_document              bool NOT NULL DEFAULT false,
    require_resource_indicator              bool NOT NULL DEFAULT false,
    allowed_access_token_signing_algorithms varchar(100),
    created                                 timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated                                 timestamptz,
    last_accessed                           timestamptz,
    non_editable                            bool NOT NULL DEFAULT false,
    CONSTRAINT uq_api_resources_name UNIQUE (name)
)
-- last_accessed is rewritten on every token validation; leave room on
-- each page so those updates stay HOT and do not fragment the index.
WITH (fillfactor = 90);

-- ---------------------------------------------------------------------
-- Clients (the applications requesting tokens)
-- ---------------------------------------------------------------------
CREATE TABLE clients (
    id                                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id                             varchar(200) NOT NULL,
    client_name                           varchar(200),
    protocol_type                         varchar(200) NOT NULL DEFAULT 'oidc',
    enabled                               bool NOT NULL DEFAULT true,
    description                           varchar(1000),
    client_uri                            varchar(2000),
    logo_uri                              varchar(2000),
    require_client_secret                 bool NOT NULL DEFAULT true,
    require_pkce                          bool NOT NULL DEFAULT true,
    allow_plain_text_pkce                 bool NOT NULL DEFAULT false,
    require_request_object                bool NOT NULL DEFAULT false,
    allow_offline_access                  bool NOT NULL DEFAULT false,
    -- Lifetimes (seconds)
    access_token_lifetime                 int4 NOT NULL DEFAULT 3600,
    authorization_code_lifetime           int4 NOT NULL DEFAULT 300,
    identity_token_lifetime               int4 NOT NULL DEFAULT 300,
    refresh_token_usage                   int4 NOT NULL DEFAULT 1,
    refresh_token_expiration              int4 NOT NULL DEFAULT 1,
    absolute_refresh_token_lifetime       int4 NOT NULL DEFAULT 2592000,
    sliding_refresh_token_lifetime        int4 NOT NULL DEFAULT 1296000,
    -- Advanced / modern fields
    ciba_lifetime                         int4,
    polling_interval                      int4,
    coordinate_lifetime_with_user_session bool,
    require_dpop                          bool NOT NULL DEFAULT false,
    dpop_validation_mode                  int4 NOT NULL DEFAULT 0,
    dpop_clock_skew                       interval NOT NULL DEFAULT '00:00:00',
    initiate_login_uri                    varchar(2000),
    pushed_authorization_lifetime         int4,
    require_pushed_authorization          bool NOT NULL DEFAULT false,
    created                               timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated                               timestamptz,
    last_accessed                         timestamptz,
    non_editable                          bool NOT NULL DEFAULT false,
    CONSTRAINT uq_clients_client_id UNIQUE (client_id),
    -- A zero or negative lifetime silently issues already-expired
    -- tokens, which is near-impossible to diagnose from the client side.
    CONSTRAINT ck_clients_access_token_lifetime       CHECK (access_token_lifetime > 0),
    CONSTRAINT ck_clients_authorization_code_lifetime CHECK (authorization_code_lifetime > 0),
    CONSTRAINT ck_clients_identity_token_lifetime     CHECK (identity_token_lifetime > 0),
    CONSTRAINT ck_clients_refresh_lifetimes           CHECK (
        absolute_refresh_token_lifetime > 0
        AND sliding_refresh_token_lifetime > 0
        AND sliding_refresh_token_lifetime <= absolute_refresh_token_lifetime
    ),
    CONSTRAINT ck_clients_dpop_clock_skew             CHECK (dpop_clock_skew >= interval '0'),
    -- PKCE without a code challenge method is not PKCE; plain text is
    -- only meaningful when PKCE is on at all.
    CONSTRAINT ck_clients_plain_text_pkce             CHECK (NOT allow_plain_text_pkce OR require_pkce)
)
WITH (fillfactor = 90);

-- ---------------------------------------------------------------------
-- API Scopes (individual permissions)
-- ---------------------------------------------------------------------
CREATE TABLE api_scopes (
    id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                       varchar(200) NOT NULL,
    display_name               varchar(200),
    description                varchar(1000),
    enabled                    bool NOT NULL DEFAULT true,
    required                   bool NOT NULL DEFAULT false,
    emphasize                  bool NOT NULL DEFAULT false,
    show_in_discovery_document bool NOT NULL DEFAULT true,
    created                    timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated                    timestamptz,
    last_accessed              timestamptz,
    non_editable               bool NOT NULL DEFAULT false,
    CONSTRAINT uq_api_scopes_name UNIQUE (name)
)
WITH (fillfactor = 90);

-- ---------------------------------------------------------------------
-- Identity Resources (OIDC claims groups: openid, profile, email)
-- ---------------------------------------------------------------------
CREATE TABLE identity_resources (
    id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                       varchar(200) NOT NULL,
    display_name               varchar(200),
    description                varchar(1000),
    enabled                    bool NOT NULL DEFAULT true,
    required                   bool NOT NULL DEFAULT false,
    emphasize                  bool NOT NULL DEFAULT false,
    show_in_discovery_document bool NOT NULL DEFAULT true,
    created                    timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated                    timestamptz,
    non_editable               bool NOT NULL DEFAULT false,
    CONSTRAINT uq_identity_resources_name UNIQUE (name)
);

-- ---------------------------------------------------------------------
-- Identity Providers (external auth: Google, Microsoft, Okta)
-- ---------------------------------------------------------------------
CREATE TABLE identity_providers (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme        varchar(200) NOT NULL,
    display_name  varchar(200),
    enabled       bool NOT NULL DEFAULT true,
    type          varchar(20) NOT NULL,
    -- jsonb, not text: the provider blob is queried by key (authority,
    -- client_id, ...) and jsonb both validates it on write and can be
    -- indexed. A malformed blob now fails at INSERT, not at login.
    properties    jsonb,
    created       timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated       timestamptz,
    last_accessed timestamptz,
    non_editable  bool NOT NULL DEFAULT false,
    -- This UNIQUE replaces the old separate ix_identity_providers_scheme
    -- index, which duplicated the column's own UNIQUE constraint: two
    -- identical btrees maintained on every write.
    CONSTRAINT uq_identity_providers_scheme UNIQUE (scheme),
    CONSTRAINT ck_identity_providers_properties_object
        CHECK (properties IS NULL OR jsonb_typeof(properties) = 'object')
)
WITH (fillfactor = 90);

-- ---------------------------------------------------------------------
-- Client relationships
--
-- Each UNIQUE below leads with client_id, so it doubles as the FK index
-- for ON DELETE CASCADE and as the ON CONFLICT arbiter used by seed.sql.
-- ---------------------------------------------------------------------
CREATE TABLE client_scopes (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope     varchar(200) NOT NULL,
    client_id bigint NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    CONSTRAINT uq_client_scopes UNIQUE (client_id, scope)
);

CREATE TABLE client_redirect_uris (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    redirect_uri varchar(400) NOT NULL,
    client_id    bigint NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    CONSTRAINT uq_client_redirect_uris UNIQUE (client_id, redirect_uri)
);

CREATE TABLE client_post_logout_redirect_uris (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_logout_redirect_uri varchar(400) NOT NULL,
    client_id                bigint NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    CONSTRAINT uq_client_post_logout_redirect_uris UNIQUE (client_id, post_logout_redirect_uri)
);

CREATE TABLE client_grant_types (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_type varchar(250) NOT NULL,
    client_id  bigint NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    CONSTRAINT uq_client_grant_types UNIQUE (client_id, grant_type)
);

CREATE TABLE client_secrets (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    value       varchar(4000) NOT NULL,
    description varchar(2000),
    expiration  timestamptz,
    type        varchar(250) NOT NULL,
    created     timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    client_id   bigint NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    CONSTRAINT uq_client_secrets UNIQUE (client_id, type, value)
);

-- Secret validation fetches a client's secrets and discards expired
-- ones. expiration trails client_id so that filtering happens inside
-- the index. It cannot be a partial index: a WHERE clause comparing
-- against CURRENT_TIMESTAMP is rejected, because index predicates must
-- be IMMUTABLE and "now" is not.
CREATE INDEX ix_client_secrets_client_expiration
    ON client_secrets (client_id, expiration);

CREATE TABLE client_claims (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type      varchar(250) NOT NULL,
    value     varchar(250) NOT NULL,
    client_id bigint NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    CONSTRAINT uq_client_claims UNIQUE (client_id, type, value)
);

CREATE TABLE client_cors_origins (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin    varchar(150) NOT NULL,
    client_id bigint NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    CONSTRAINT uq_client_cors_origins UNIQUE (client_id, origin)
);

-- CORS preflight asks "is this origin allowed for anyone?" on every
-- cross-site request, which is a lookup by origin, not by client.
CREATE INDEX ix_client_cors_origins_origin ON client_cors_origins (origin);

CREATE TABLE client_idp_restrictions (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider  varchar(200) NOT NULL,
    client_id bigint NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    CONSTRAINT uq_client_idp_restrictions UNIQUE (client_id, provider)
);

CREATE TABLE client_properties (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key       varchar(250) NOT NULL,
    value     varchar(2000) NOT NULL,
    client_id bigint NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    CONSTRAINT uq_client_properties UNIQUE (client_id, key)
);

-- ---------------------------------------------------------------------
-- API Resource relationships
-- ---------------------------------------------------------------------
CREATE TABLE api_resource_scopes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope           varchar(200) NOT NULL,
    api_resource_id bigint NOT NULL REFERENCES api_resources(id) ON DELETE CASCADE,
    CONSTRAINT uq_api_resource_scopes UNIQUE (api_resource_id, scope)
);

CREATE TABLE api_resource_claims (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            varchar(200) NOT NULL,
    api_resource_id bigint NOT NULL REFERENCES api_resources(id) ON DELETE CASCADE,
    CONSTRAINT uq_api_resource_claims UNIQUE (api_resource_id, type)
);

CREATE TABLE api_resource_secrets (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    value           varchar(4000) NOT NULL,
    description     varchar(1000),
    expiration      timestamptz,
    type            varchar(250) NOT NULL,
    created         timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    api_resource_id bigint NOT NULL REFERENCES api_resources(id) ON DELETE CASCADE,
    CONSTRAINT uq_api_resource_secrets UNIQUE (api_resource_id, type, value)
);

-- Introspection authenticates the resource server on every call; same
-- IMMUTABLE restriction as ix_client_secrets_client_expiration above.
CREATE INDEX ix_api_resource_secrets_resource_expiration
    ON api_resource_secrets (api_resource_id, expiration);

CREATE TABLE api_resource_properties (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key             varchar(250) NOT NULL,
    value           varchar(2000) NOT NULL,
    api_resource_id bigint NOT NULL REFERENCES api_resources(id) ON DELETE CASCADE,
    CONSTRAINT uq_api_resource_properties UNIQUE (api_resource_id, key)
);

-- ---------------------------------------------------------------------
-- API Scope relationships
-- ---------------------------------------------------------------------
CREATE TABLE api_scope_claims (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type     varchar(200) NOT NULL,
    scope_id bigint NOT NULL REFERENCES api_scopes(id) ON DELETE CASCADE,
    CONSTRAINT uq_api_scope_claims UNIQUE (scope_id, type)
);

CREATE TABLE api_scope_properties (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key      varchar(250) NOT NULL,
    value    varchar(2000) NOT NULL,
    scope_id bigint NOT NULL REFERENCES api_scopes(id) ON DELETE CASCADE,
    CONSTRAINT uq_api_scope_properties UNIQUE (scope_id, key)
);

-- ---------------------------------------------------------------------
-- Identity Resource relationships
-- ---------------------------------------------------------------------
CREATE TABLE identity_resource_claims (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                 varchar(200) NOT NULL,
    identity_resource_id bigint NOT NULL REFERENCES identity_resources(id) ON DELETE CASCADE,
    CONSTRAINT uq_identity_resource_claims UNIQUE (identity_resource_id, type)
);

CREATE TABLE identity_resource_properties (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key                  varchar(250) NOT NULL,
    value                varchar(2000) NOT NULL,
    identity_resource_id bigint NOT NULL REFERENCES identity_resources(id) ON DELETE CASCADE,
    CONSTRAINT uq_identity_resource_properties UNIQUE (identity_resource_id, key)
);

-- ---------------------------------------------------------------------
-- Discovery-document lookups
--
-- The discovery endpoint and token issuance read only enabled rows, so
-- these are partial: the index holds live configuration only.
-- ---------------------------------------------------------------------
CREATE INDEX ix_api_scopes_discoverable
    ON api_scopes (name) WHERE enabled AND show_in_discovery_document;

CREATE INDEX ix_identity_resources_discoverable
    ON identity_resources (name) WHERE enabled AND show_in_discovery_document;

CREATE INDEX ix_clients_enabled ON clients (client_id) WHERE enabled;

CREATE INDEX ix_identity_providers_enabled ON identity_providers (scheme) WHERE enabled;

COMMIT;
