-- =====================================================================
-- Operational store: device codes, signing keys, grants, PAR, sessions
-- Target: PostgreSQL 19
--
-- These tables differ from the configuration store in one way that
-- drives every decision below: rows are written once, read a handful of
-- times, then deleted. Churn, not volume, is the problem. So each hot
-- table carries its own autovacuum settings instead of inheriting
-- cluster defaults tuned for tables that mostly sit still.
-- =====================================================================

START TRANSACTION;

-- Replaces a DO block that queried pg_namespace by hand. Same effect,
-- and it no longer silently does the wrong thing if the name exists as
-- something other than a schema.
CREATE SCHEMA IF NOT EXISTS idmgmt;

-- ---------------------------------------------------------------------
-- Device codes (RFC 8628 device authorization grant)
--
-- Written at device-flow start, polled until redeemed, then deleted.
-- ---------------------------------------------------------------------
CREATE TABLE idmgmt.device_codes (
    user_code     varchar(200) NOT NULL,
    device_code   varchar(200) NOT NULL,
    subject_id    varchar(200),
    session_id    varchar(100),
    client_id     varchar(200) NOT NULL,
    description   varchar(200),
    creation_time timestamptz NOT NULL DEFAULT now(),
    expiration    timestamptz NOT NULL,
    -- text, not varchar(50000). The length cap bought nothing: the value
    -- is a serialised blob of unpredictable size, and anything over
    -- ~2 KB goes out to TOAST either way. In PostgreSQL 19 TOAST
    -- compresses with lz4 by default, so this needs no COMPRESSION
    -- clause to get the faster codec.
    data          text NOT NULL,
    CONSTRAINT pk_device_codes PRIMARY KEY (user_code),
    CONSTRAINT uq_device_codes_device_code UNIQUE (device_code),
    CONSTRAINT ck_device_codes_expiration CHECK (expiration > creation_time)
)
WITH (
    fillfactor                            = 85,
    autovacuum_vacuum_scale_factor        = 0.02,
    autovacuum_vacuum_threshold           = 200,
    autovacuum_vacuum_insert_scale_factor = 0.02,
    autovacuum_analyze_scale_factor       = 0.05
);

-- Expiry sweeps scan by expiration. No partial clause: every row has an
-- expiration (it is NOT NULL), so a partial index would exclude nothing.
CREATE INDEX ix_device_codes_expiration ON idmgmt.device_codes (expiration);

-- ---------------------------------------------------------------------
-- Signing keys
--
-- The one table here that is effectively read-only: a handful of rows,
-- read on every token signature, written only on key rotation.
-- ---------------------------------------------------------------------
CREATE TABLE idmgmt.keys (
    id                  text NOT NULL,
    version             integer NOT NULL,
    created             timestamptz NOT NULL DEFAULT now(),
    use                 text,
    algorithm           varchar(100) NOT NULL,
    is_x509_certificate boolean NOT NULL DEFAULT false,
    data_protected      boolean NOT NULL DEFAULT false,
    data                text NOT NULL,
    CONSTRAINT pk_keys PRIMARY KEY (id)
);

-- Key selection asks for the newest key for a given use. Ordering the
-- index by created DESC lets that be a one-row index scan rather than
-- "read every key of this use, then sort".
CREATE INDEX ix_keys_use_created ON idmgmt.keys (use, created DESC);

-- ---------------------------------------------------------------------
-- Persisted grants (refresh tokens, reference tokens, consent)
--
-- The highest-churn table in the schema.
-- ---------------------------------------------------------------------
CREATE TABLE idmgmt.persisted_grants (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    key           varchar(200),
    type          varchar(50) NOT NULL,
    subject_id    varchar(200),
    session_id    varchar(100),
    client_id     varchar(200) NOT NULL,
    description   varchar(200),
    creation_time timestamptz NOT NULL DEFAULT now(),
    expiration    timestamptz,
    consumed_time timestamptz,
    data          text NOT NULL,
    CONSTRAINT pk_persisted_grants PRIMARY KEY (id),
    CONSTRAINT uq_persisted_grants_key UNIQUE (key)
)
WITH (
    -- consumed_time is stamped in place when a refresh token is used,
    -- so this table is update-heavy as well as insert-heavy.
    fillfactor                            = 80,
    autovacuum_vacuum_scale_factor        = 0.01,
    autovacuum_vacuum_threshold           = 500,
    autovacuum_vacuum_insert_scale_factor = 0.01,
    autovacuum_analyze_scale_factor       = 0.02,
    -- PostgreSQL 19: lets autovacuum vacuum this table's several
    -- indexes in parallel. NOTE: this is capped by the cluster-level
    -- autovacuum_max_parallel_workers, which DEFAULTS TO 0 -- so this
    -- has no effect until that is raised in postgresql.conf. Left here
    -- deliberately, so the per-table intent is recorded where the table
    -- is defined. -1 would mean "inherit".
    autovacuum_parallel_workers           = 2
);

-- Revocation and consent lookups always qualify by subject.
CREATE INDEX ix_persisted_grants_subject_id_client_id_type
    ON idmgmt.persisted_grants (subject_id, client_id, type);

CREATE INDEX ix_persisted_grants_subject_id_session_id_type
    ON idmgmt.persisted_grants (subject_id, session_id, type);

-- Both of these serve cleanup sweeps, and both are partial: a grant
-- with no expiration never expires, and an unconsumed grant has
-- consumed_time NULL. Excluding those rows keeps each index to the
-- subset the sweep actually reads.
CREATE INDEX ix_persisted_grants_expiration
    ON idmgmt.persisted_grants (expiration)
    WHERE expiration IS NOT NULL;

CREATE INDEX ix_persisted_grants_consumed_time
    ON idmgmt.persisted_grants (consumed_time)
    WHERE consumed_time IS NOT NULL;

-- ---------------------------------------------------------------------
-- Pushed authorization requests (RFC 9126)
--
-- The shortest-lived rows of all: written at pushed-request time, read
-- once at the authorize endpoint, then expired.
-- ---------------------------------------------------------------------
CREATE TABLE idmgmt.pushed_authorization_requests (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY,
    reference_value_hash varchar(64) NOT NULL,
    expires_at_utc       timestamptz NOT NULL,
    parameters           text NOT NULL,
    CONSTRAINT pk_pushed_authorization_requests PRIMARY KEY (id),
    CONSTRAINT uq_pushed_authorization_requests_reference_value_hash
        UNIQUE (reference_value_hash)
)
WITH (
    fillfactor                            = 85,
    autovacuum_vacuum_scale_factor        = 0.01,
    autovacuum_vacuum_threshold           = 500,
    autovacuum_vacuum_insert_scale_factor = 0.01,
    autovacuum_analyze_scale_factor       = 0.02
);

CREATE INDEX ix_pushed_authorization_requests_expires_at_utc
    ON idmgmt.pushed_authorization_requests (expires_at_utc);

-- ---------------------------------------------------------------------
-- Server-side sessions
--
-- Updated on every request that renews a session, so the most
-- update-heavy table here.
-- ---------------------------------------------------------------------
CREATE TABLE idmgmt.server_side_sessions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    key          varchar(100) NOT NULL,
    scheme       varchar(100) NOT NULL,
    subject_id   varchar(100) NOT NULL,
    session_id   varchar(100),
    display_name varchar(100),
    created      timestamptz NOT NULL DEFAULT now(),
    renewed      timestamptz NOT NULL DEFAULT now(),
    expires      timestamptz,
    data         text NOT NULL,
    CONSTRAINT pk_server_side_sessions PRIMARY KEY (id),
    CONSTRAINT uq_server_side_sessions_key UNIQUE (key)
)
WITH (
    -- Lowest fillfactor in the schema: renewed and data are rewritten
    -- repeatedly for the same row, and leaving a fifth of each page free
    -- lets those updates stay on-page (HOT) instead of migrating the row
    -- and touching every index.
    fillfactor                            = 80,
    autovacuum_vacuum_scale_factor        = 0.01,
    autovacuum_vacuum_threshold           = 500,
    autovacuum_vacuum_insert_scale_factor = 0.01,
    autovacuum_analyze_scale_factor       = 0.02,
    autovacuum_parallel_workers           = 2
);

CREATE INDEX ix_server_side_sessions_subject_id
    ON idmgmt.server_side_sessions (subject_id);

CREATE INDEX ix_server_side_sessions_session_id
    ON idmgmt.server_side_sessions (session_id)
    WHERE session_id IS NOT NULL;

CREATE INDEX ix_server_side_sessions_display_name
    ON idmgmt.server_side_sessions (display_name)
    WHERE display_name IS NOT NULL;

CREATE INDEX ix_server_side_sessions_expires
    ON idmgmt.server_side_sessions (expires)
    WHERE expires IS NOT NULL;

COMMIT;
