-- =====================================================================
-- Users, roles and claims
-- Target: PostgreSQL 19
--
-- Notable choices:
--   * normalized_* columns are GENERATED ... STORED, so the database
--     derives them rather than trusting every writer to remember. A
--     row whose normalized form disagrees with its source is no longer
--     representable.
--   * uuidv7() primary keys (PostgreSQL 18+) are time-ordered, so
--     inserts append to the right-hand edge of the index instead of
--     scattering writes across it the way uuidv4 does.
-- =====================================================================

START TRANSACTION;

-- Case-insensitive text, used for email so that comparison and
-- uniqueness do not depend on the caller folding case correctly.
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE roles (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    role_id           uuid NOT NULL DEFAULT uuidv7(),
    name              varchar(256) NOT NULL,
    -- STORED, not VIRTUAL. In PostgreSQL 19 a generated column with no
    -- keyword defaults to VIRTUAL, which is computed on read; a UNIQUE
    -- constraint needs the value materialised, so STORED is explicit.
    normalized_name   varchar(256) GENERATED ALWAYS AS (upper(name)) STORED,
    concurrency_stamp uuid NOT NULL DEFAULT uuidv7(),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_roles PRIMARY KEY (role_id),
    CONSTRAINT uq_roles_id UNIQUE (id),
    CONSTRAINT uq_roles_name UNIQUE (name),
    CONSTRAINT uq_roles_normalized_name UNIQUE (normalized_name),
    CONSTRAINT ck_roles_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE users (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id                uuid NOT NULL DEFAULT uuidv7(),
    user_name              varchar(256) NOT NULL,
    normalized_user_name   varchar(256) GENERATED ALWAYS AS (upper(user_name)) STORED,
    email                  citext NOT NULL,
    email_confirmed        boolean NOT NULL DEFAULT false,
    password_hash          text,
    security_stamp         uuid NOT NULL DEFAULT uuidv7(),
    concurrency_stamp      uuid NOT NULL DEFAULT uuidv7(),
    phone_number           varchar(20),
    phone_number_confirmed boolean NOT NULL DEFAULT false,
    two_factor_enabled     boolean NOT NULL DEFAULT false,
    lockout_end            timestamptz,
    lockout_enabled        boolean NOT NULL DEFAULT false,
    access_failed_count    integer NOT NULL DEFAULT 0,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_id UNIQUE (id),
    CONSTRAINT uq_users_user_name UNIQUE (user_name),
    CONSTRAINT uq_users_normalized_user_name UNIQUE (normalized_user_name),
    -- email is citext, so this one UNIQUE is already case-insensitive.
    -- The old separate idx_users_email duplicated it exactly and has
    -- been dropped: it cost a second btree on every insert and update
    -- and could never be chosen over the unique index.
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_access_failed_count CHECK (access_failed_count >= 0),
    CONSTRAINT ck_users_user_name_not_blank CHECK (btrim(user_name) <> ''),
    -- '@' alone is a deliberately weak check: anything stricter rejects
    -- addresses that are in fact valid. Real validation belongs at the
    -- point of capture; this only catches obvious junk.
    CONSTRAINT ck_users_email_shape CHECK (position('@' in email) > 1)
)
-- Login traffic rewrites access_failed_count, lockout_end and the
-- stamps far more often than it inserts users; the spare page room
-- keeps those updates HOT.
WITH (fillfactor = 85);

CREATE TABLE role_claims (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id     uuid NOT NULL REFERENCES roles(role_id) ON DELETE CASCADE,
    claim_type  varchar(256) NOT NULL,
    claim_value text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE user_claims (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     uuid NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    claim_type  varchar(256) NOT NULL,
    claim_value text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

-- External login associations (Google, Facebook, ...)
CREATE TABLE user_logins (
    login_provider        varchar(128) NOT NULL,
    provider_key          varchar(256) NOT NULL,
    provider_display_name varchar(256),
    user_id               uuid NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    created_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_logins PRIMARY KEY (login_provider, provider_key)
);

CREATE TABLE user_roles (
    user_id    uuid NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    role_id    uuid NOT NULL REFERENCES roles(role_id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id)
);

CREATE TABLE user_tokens (
    user_id        uuid NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    login_provider varchar(128) NOT NULL,
    name           varchar(128) NOT NULL,
    value          text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_tokens PRIMARY KEY (user_id, login_provider, name)
);

-- ---------------------------------------------------------------------
-- Indexes
--
-- Only the foreign keys NOT already led by an existing index are listed.
-- user_tokens(user_id) is covered by its primary key, so it is absent
-- here on purpose rather than by omission.
--
-- Claims are deliberately NOT unique per (subject, claim_type): a
-- subject may legitimately hold several values for one type, so these
-- are plain indexes that cover the foreign key and serve lookup by type.
-- ---------------------------------------------------------------------

-- user_logins is keyed by (login_provider, provider_key), so user_id
-- needs its own index for "delete this user" to avoid a seq scan.
CREATE INDEX ix_role_claims_role_claim_type ON role_claims (role_id, claim_type);
CREATE INDEX ix_user_claims_user_claim_type ON user_claims (user_id, claim_type);

CREATE INDEX ix_user_logins_user_id ON user_logins (user_id);

-- user_roles is keyed by (user_id, role_id); the reverse direction
-- ("who holds this role?") and cascading role deletes need role_id.
CREATE INDEX ix_user_roles_role_id ON user_roles (role_id);

-- Lockout sweeps look only at users currently locked out, which is a
-- tiny fraction of the table. Partial, so the index stays small.
CREATE INDEX ix_users_lockout_active
    ON users (lockout_end)
    WHERE lockout_enabled AND lockout_end IS NOT NULL;

-- Unconfirmed registrations are what reminder and cleanup jobs scan.
CREATE INDEX ix_users_unconfirmed
    ON users (created_at)
    WHERE NOT email_confirmed;

-- ---------------------------------------------------------------------
-- updated_at maintenance
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
-- A trigger function runs with the caller's search_path unless pinned.
-- Pinning it means an attacker who can create objects in a schema
-- earlier on that path cannot shadow now() or btrim() here.
SECURITY INVOKER
SET search_path = pg_catalog, pg_temp
AS $fn$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$fn$;

-- The WHEN clause is the point of this rewrite: an UPDATE that changes
-- nothing no longer bumps updated_at, so it writes no new row version,
-- dirties no page and leaves nothing for vacuum to clean up.
--
-- The columns are listed out rather than written as the far shorter
-- OLD.* IS DISTINCT FROM NEW.* because a BEFORE trigger may not use a
-- whole-row reference on a table that has generated columns -- the
-- generated values do not exist yet at BEFORE time. normalized_name
-- and normalized_user_name are therefore absent by necessity, which
-- costs nothing: each is a pure function of a column already compared.
-- updated_at is also excluded on purpose, so that a write touching only
-- updated_at does not count as a change and re-trigger.
CREATE TRIGGER trg_roles_updated_at
    BEFORE UPDATE ON roles
    FOR EACH ROW
    WHEN ((OLD.id, OLD.role_id, OLD.name, OLD.concurrency_stamp, OLD.created_at)
          IS DISTINCT FROM
          (NEW.id, NEW.role_id, NEW.name, NEW.concurrency_stamp, NEW.created_at))
    EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW
    WHEN ((OLD.id, OLD.user_id, OLD.user_name, OLD.email, OLD.email_confirmed,
           OLD.password_hash, OLD.security_stamp, OLD.concurrency_stamp,
           OLD.phone_number, OLD.phone_number_confirmed, OLD.two_factor_enabled,
           OLD.lockout_end, OLD.lockout_enabled, OLD.access_failed_count,
           OLD.created_at)
          IS DISTINCT FROM
          (NEW.id, NEW.user_id, NEW.user_name, NEW.email, NEW.email_confirmed,
           NEW.password_hash, NEW.security_stamp, NEW.concurrency_stamp,
           NEW.phone_number, NEW.phone_number_confirmed, NEW.two_factor_enabled,
           NEW.lockout_end, NEW.lockout_enabled, NEW.access_failed_count,
           NEW.created_at))
    EXECUTE FUNCTION set_updated_at();

COMMIT;

